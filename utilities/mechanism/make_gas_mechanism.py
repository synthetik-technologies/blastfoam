#!/usr/bin/env python3
"""
make_gas_mechanism.py: finite-rate gas mechanism for the Comp-B/Al gas phase
below the equilibrium temperature Teq (plan step C6).

    python3 make_gas_mechanism.py --species O2 N2 CO ... -o constant/reactions.gas
        [--gri <OpenFOAM GRI-3.0 reactions file>] [--no-al]

Reactions:
- H2/O2/CO and C1: all reactions of GRI-3.0 among H2, O2, H, O, OH, H2O,
  HO2, H2O2, CO, CO2, CH4, CH3, CH2O, HCO, CH3O and C2H6, with N2 as an
  explicit collision partner (H + O2 + N2 = HO2 + N2); reversible, third-body
  and fall-off reactions with the GRI efficiencies (1 for the other species
  of the phase). The rates are taken from the OpenFOAM conversion of GRI-3.0
  (SI units, kmol) shipped with OpenFOAM (tutorials/multicomponentFluid/
  counterFlowFlame2DLTS_GRI_TDAC). Reverse rates follow from the phase
  thermodynamics (nasa9), the same data as the equilibrium solver above Teq.
  The CH4 oxidation through CH3/CH2O/HCO reproduces the inhibition of the
  ignition by CH4 (radical scavenging), which global CH4 steps (e.g. Jones
  and Lindstedt) miss: with them the products/air mixture ignited 4 times
  too early compared with the full GRI-3.0 mechanism.
- Al (unless --no-al): the global oxidation steps of the spherical Comp-B/Al
  cases (Al + O2, CO2, H2O -> Al2O3(s)), unchanged.
NH3, N, NO, AlO and the condensed species have no finite-rate reactions (they
react only in the equilibrium regime above Teq).
"""

import argparse
import os
import re
import sys

GRI = os.path.join(
    os.environ.get("FOAM_TUTORIALS", "/opt/OpenFOAM/OpenFOAM-12/tutorials"),
    "multicomponentFluid/counterFlowFlame2DLTS_GRI_TDAC/constant/reactionsGRI",
)
HOC = {"H2", "O2", "H", "O", "OH", "H2O", "HO2", "H2O2", "CO", "CO2",
       "CH4", "CH3", "CH2O", "HCO", "CH3O", "C2H6"}

AL_REACTIONS = """    Al_O2_Reaction
    {
        type     irreversibleArrhenius;
        reaction "4Al + 3O2 = 2Al2O3(s)";
        A        1.0e13;
        beta     0;
        Ta       15000;
    }
    Al_CO2_Reaction
    {
        type     irreversibleArrhenius;
        reaction "2Al + 3CO2 = Al2O3(s) + 3CO";
        A        6.0e12;
        beta     0;
        Ta       19000;
    }
    Al_H2O_Reaction
    {
        type     irreversibleArrhenius;
        reaction "2Al + 3H2O = Al2O3(s) + 3H2";
        A        8.0e12;
        beta     0;
        Ta       17500;
    }
"""


def reaction_species(eq):
    names = set()
    for side in re.split(r"=", eq):
        for term in side.split(" + "):
            term = term.strip().split("^")[0]
            m = re.match(r"^[0-9.]*(.+)$", term)
            names.add(m.group(1))
    return names


def gri_reactions(path, species):
    text = open(path).read()
    body = text[text.index("reactions"):]
    blocks = re.findall(r"\n    (un-named-reaction-\d+)\n    \{\n(.*?)\n    \}", body, re.S)
    out = []
    for name, blk in blocks:
        eq = re.search(r'reaction\s+"([^"]+)"', blk).group(1)
        if not reaction_species(eq) <= HOC | {"N2"}:
            continue

        def efficiencies(m):
            gri = dict(re.findall(r"\(([^\s()]+(?:\([a-zA-Z]+\))?) ([0-9.eE+-]+)\)", m.group(2)))
            rows = "\n".join(f"({s} {gri.get(s, '1')})" for s in species)
            return f"{m.group(1)}\n{len(species)}\n(\n{rows}\n)\n"
        blk = re.sub(r"(\s*coeffs)\n\d+\n\((.*?)\n\)\n", efficiencies, blk, flags=re.S)
        out.append(f"    {name}\n    {{\n{blk}\n    }}\n")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--species", nargs="+", required=True, help="species of the gas phase")
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--gri", default=GRI)
    ap.add_argument("--no-al", action="store_true")
    a = ap.parse_args()

    missing = (HOC | {"N2"}) - set(a.species)
    if missing:
        sys.exit(f"Species missing from the phase: {sorted(missing)}")
    if not os.path.isfile(a.gri):
        sys.exit(f"GRI-3.0 reactions not found: {a.gri}")

    gri = gri_reactions(a.gri, a.species)
    hdr = """/*--------------------------------*- C++ -*----------------------------------*\\
  =========                 |
  \\\\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox
   \\\\    /   O peration     | Website:  https://openfoam.org
    \\\\  /    A nd           | Version:  12
     \\\\/     M anipulation  |
\\*---------------------------------------------------------------------------*/
// Generated by utilities/mechanism/make_gas_mechanism.py: GRI-3.0 H2/O2/CO
// and C1 subset (reversible)"""
    hdr += "" if a.no_al else ", global Al oxidation"
    hdr += "\n\n"
    species = "species\n(\n" + "".join(f"    {s}\n" for s in a.species) + ");\n\n"
    body = "reactions\n{\n" + "".join(gri) + ("" if a.no_al else AL_REACTIONS) + "}\n"
    with open(a.output, "w") as f:
        f.write(hdr + species + body
                + "\n// ************************************************************************* //\n")
    print(f"{len(gri)} GRI-3.0 H2/O2/CO/C1 reactions"
          + ("" if a.no_al else ", 3 Al steps") + f" -> {a.output}")


if __name__ == "__main__":
    main()
